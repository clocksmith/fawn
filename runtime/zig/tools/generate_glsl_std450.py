"""Generate GLSL extended-instruction names from the pinned Khronos header."""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT / "vendor/spirv-headers/GLSL.std.450.h"
OUTPUT = ROOT / "src/compiler/wgsl/emit/spirv/glsl_std450.zig"
SOURCE_COMMIT = "86f980c731e62ae4eaf383d320449d71687936bf"
HEADER_SHA256 = "d18a932ee97c268a57e33134651d554dbe71a5654b975e89e9e9487fa59ac9df"


def render() -> str:
    data = HEADER.read_bytes()
    if hashlib.sha256(data).hexdigest() != HEADER_SHA256:
        raise ValueError("Pinned GLSL.std.450.h content changed")
    entries = re.findall(r"^\s+GLSLstd450(\w+) = (\d+),", data.decode(), re.MULTILINE)
    if not entries or len(dict(entries)) != len(entries):
        raise ValueError("Missing or duplicate GLSL extended instructions")
    return (
        "// Generated by tools/generate_glsl_std450.py; do not edit.\n"
        "// SPDX-FileCopyrightText: 2014-2024 The Khronos Group Inc.\n"
        "// SPDX-License-Identifier: MIT\n"
        f"// SPIRV-Headers commit {SOURCE_COMMIT}; see vendor/spirv-headers.\n\n"
        + "".join(f"pub const {name}: u32 = {number};\n" for name, number in entries)
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != expected:
            raise ValueError("Stale GLSL definitions; run tools/generate_glsl_std450.py")
    else:
        OUTPUT.write_text(expected, encoding="utf-8")


if __name__ == "__main__":
    main()
