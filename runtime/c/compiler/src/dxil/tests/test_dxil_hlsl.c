static void check_decimals(void) {
    static const struct { double value; const char *text; } cases[] = {
        {0.0, "0.0"}, {-0.0, "-0.0"}, {0.5, "0.5"},
        {1e-7, "0.0000001"}, {1e20, "100000000000000000000.0"},
        {1.2345678901234567, "1.2345678901234567"}
    };
    static const char *const locales[] = {"C", "de_DE.utf8", "fr_FR.utf8"};
    fenv_t saved;
    CHECK(fegetenv(&saved) == 0);
    for (size_t locale_index = 0u; locale_index < sizeof(locales)/sizeof(locales[0]); ++locale_index) {
        if (setlocale(LC_NUMERIC, locales[locale_index]) == NULL) {
            printf("SKIP unavailable numeric locale %s\n", locales[locale_index]);
            continue;
        }
        for (size_t i = 0u; i < sizeof(cases)/sizeof(cases[0]); ++i) {
            char text[128] = {0};
            DxilHlslEmitter emitter = {.out = text, .out_len = sizeof(text)};
            CHECK(fesetround(FE_DOWNWARD) == 0);
            CHECK(feraiseexcept(FE_INVALID) == 0);
            const int exceptions = fetestexcept(FE_ALL_EXCEPT);
            errno = ERANGE;
            CHECK_STATUS(dxil_hlsl_write_float(&emitter, cases[i].value), DXIL_OK);
            CHECK(errno == ERANGE && fegetround() == FE_DOWNWARD);
            CHECK(fetestexcept(FE_ALL_EXCEPT) == exceptions);
            CHECK(emitter.pos == strlen(cases[i].text));
            CHECK(memcmp(text, cases[i].text, emitter.pos) == 0);
        }
    }
    CHECK(setlocale(LC_NUMERIC, "C") != NULL);
    char text[128];
    memset(text, '?', sizeof(text));
    DxilHlslEmitter emitter = {.out = text, .out_len = sizeof(text)};
    CHECK_STATUS(dxil_hlsl_write_float(&emitter, 1e-100), DXIL_OUTPUT_TOO_LARGE);
    CHECK(emitter.pos == 0u && text[0] == '?');
    CHECK_STATUS(dxil_hlsl_write_float(&emitter, INFINITY), DXIL_INVALID_IR);
    CHECK_STATUS(dxil_hlsl_write_float(&emitter, NAN), DXIL_INVALID_IR);
    CHECK(emitter.pos == 0u && text[0] == '?');
    emitter.out_len = 1u;
    CHECK_STATUS(dxil_hlsl_write_float(&emitter, 0.5), DXIL_OUTPUT_TOO_LARGE);
    CHECK(emitter.pos == 0u && text[0] == '?');
    CHECK(fesetenv(&saved) == 0);
}

int main(void) {
    check_decimals();
    check_canonical();
    check_storage_barrier_arith();
    check_dispatch_cbuffer();
    check_atomic_and_vertex();
    TEST_SUMMARY("test_dxil_hlsl");
}
