static DxilIrTypeId scalar_ty(DxilIrModule *module,
    DxilIrScalar scalar) {
    DxilIrType type;
    DxilIrTypeId id = DXIL_IR_INVALID_ID;
    memset(&type, 0, sizeof(type));
    type.kind = DXIL_IR_TYPE_SCALAR;
    type.scalar = scalar;
    if (dxil_ir_intern_type(module, &type, &id) != DXIL_OK) {
        return DXIL_IR_INVALID_ID;
    }
    return id;
}

static DxilIrTypeId vec_ty(DxilIrModule *module, DxilIrTypeId elem,
    uint8_t len) {
    DxilIrType type;
    DxilIrTypeId id = DXIL_IR_INVALID_ID;
    memset(&type, 0, sizeof(type));
    type.kind = DXIL_IR_TYPE_VECTOR;
    type.elem = elem;
    type.len = len;
    if (dxil_ir_intern_type(module, &type, &id) != DXIL_OK) {
        return DXIL_IR_INVALID_ID;
    }
    return id;
}

static DxilIrTypeId arr_ty(DxilIrModule *module, DxilIrTypeId elem,
    uint32_t len) {
    DxilIrType type;
    DxilIrTypeId id = DXIL_IR_INVALID_ID;
    memset(&type, 0, sizeof(type));
    type.kind = DXIL_IR_TYPE_ARRAY;
    type.elem = elem;
    type.has_len = true;
    type.array_len = len;
    if (dxil_ir_intern_type(module, &type, &id) != DXIL_OK) {
        return DXIL_IR_INVALID_ID;
    }
    return id;
}

static void add_compute_entry(DxilIrModule *module,
    DxilIrFunction *function) {
    DxilIrEntryPoint entry;
    memset(&entry, 0, sizeof(entry));
    entry.function = 0;
    entry.stage = DXIL_IR_STAGE_COMPUTE;
    entry.workgroup_size[0] = 64;
    entry.workgroup_size[1] = 1;
    entry.workgroup_size[2] = 1;
    dxil_ir_add_entry_point(module, &entry);
    function->has_stage = true;
    function->stage = DXIL_IR_STAGE_COMPUTE;
    function->workgroup_size[0] = 64;
    function->workgroup_size[1] = 1;
    function->workgroup_size[2] = 1;
}

static void check_canonical(void) {
    DxilIrModule module;
    DxilIrFunction *function = NULL;
    DxilIrTypeId void_ty = DXIL_IR_INVALID_ID;
    DxilIrTypeId u32_ty = DXIL_IR_INVALID_ID;
    DxilIrTypeId vec3_ty = DXIL_IR_INVALID_ID;
    DxilIrStmt block;
    DxilIrStmtId block_id = DXIL_IR_INVALID_ID;
    static char out[65536];
    size_t written = 0;
    const char *expected =
        "// Generated by doe_wgsl/dxil_hlsl\n"
        "\n"
        "[numthreads(64, 1, 1)]\n"
        "void main(uint3 gid : SV_DispatchThreadID) {\n"
        "}\n";
    dxil_ir_init(&module);
    void_ty = scalar_ty(&module, DXIL_IR_SCALAR_VOID);
    u32_ty = scalar_ty(&module, DXIL_IR_SCALAR_U32);
    vec3_ty = vec_ty(&module, u32_ty, 3);
    dxil_ir_add_function(&module, "main", void_ty, &function);
    function->params[0].name = "gid";
    function->params[0].ty = vec3_ty;
    function->params[0].has_io = true;
    function->params[0].io.builtin =
        DXIL_IR_BUILTIN_GLOBAL_INVOCATION_ID;
    function->param_count = 1;
    memset(&block, 0, sizeof(block));
    block.kind = DXIL_IR_STMT_BLOCK;
    dxil_ir_append_stmt(function, &block, &block_id);
    function->root_stmt = block_id;
    add_compute_entry(&module, function);
    CHECK_STATUS(dxil_hlsl_emit(&module, out, sizeof(out),
        &written), DXIL_OK);
    CHECK(written == strlen(expected));
    CHECK(strcmp(out, expected) == 0);
}

static void check_storage_barrier_arith(void) {
    DxilIrModule module;
    DxilIrFunction *function = NULL;
    DxilIrTypeId void_ty = DXIL_IR_INVALID_ID;
    DxilIrTypeId u32_ty = DXIL_IR_INVALID_ID;
    DxilIrTypeId vec3_ty = DXIL_IR_INVALID_ID;
    DxilIrTypeId arr_id = DXIL_IR_INVALID_ID;
    DxilIrGlobal global;
    DxilIrGlobalId global_id = DXIL_IR_INVALID_ID;
    DxilIrStmt block;
    DxilIrStmtId block_id = DXIL_IR_INVALID_ID;
    DxilIrExpr expr;
    DxilIrExprId gid_ref = DXIL_IR_INVALID_ID;
    DxilIrExprId member = DXIL_IR_INVALID_ID;
    DxilIrExprId one = DXIL_IR_INVALID_ID;
    DxilIrExprId add = DXIL_IR_INVALID_ID;
    DxilIrExprId gref = DXIL_IR_INVALID_ID;
    DxilIrExprId index = DXIL_IR_INVALID_ID;
    DxilIrExprId call = DXIL_IR_INVALID_ID;
    DxilIrStmt stmt;
    DxilIrStmtId stmt1 = DXIL_IR_INVALID_ID;
    DxilIrStmtId stmt2 = DXIL_IR_INVALID_ID;
    static char out[65536];
    size_t written = 0;
    const char *expected =
        "// Generated by doe_wgsl/dxil_hlsl\n"
        "\n"
        "RWStructuredBuffer<uint> buf : register(u0, space0);\n"
        "\n"
        "[numthreads(64, 1, 1)]\n"
        "void main(uint3 gid : SV_DispatchThreadID) {\n"
        "    GroupMemoryBarrierWithGroupSync();\n"
        "    buf[gid.x] = (gid.x + 1);\n"
        "}\n";
    dxil_ir_init(&module);
    void_ty = scalar_ty(&module, DXIL_IR_SCALAR_VOID);
    u32_ty = scalar_ty(&module, DXIL_IR_SCALAR_U32);
    vec3_ty = vec_ty(&module, u32_ty, 3);
    arr_id = arr_ty(&module, u32_ty, 4);
    memset(&global, 0, sizeof(global));
    global.name = "buf";
    global.ty = arr_id;
    global.class = DXIL_IR_GLOBAL_VAR;
    global.has_addr_space = true;
    global.addr_space = DXIL_IR_ADDR_STORAGE;
    global.has_access = true;
    global.access = DXIL_IR_ACCESS_READ_WRITE;
    global.has_binding = true;
    global.binding.group = 0;
    global.binding.binding = 0;
    dxil_ir_add_global(&module, &global, &global_id);
    dxil_ir_add_function(&module, "main", void_ty, &function);
    function->params[0].name = "gid";
    function->params[0].ty = vec3_ty;
    function->params[0].has_io = true;
    function->params[0].io.builtin =
        DXIL_IR_BUILTIN_GLOBAL_INVOCATION_ID;
    function->param_count = 1;
    memset(&expr, 0, sizeof(expr));
    expr.kind = DXIL_IR_EXPR_CALL;
    expr.ty = void_ty;
    expr.name = "workgroupBarrier";
    expr.call_kind = DXIL_IR_CALL_BUILTIN;
    dxil_ir_append_expr(function, &expr, &call);
    memset(&stmt, 0, sizeof(stmt));
    stmt.kind = DXIL_IR_STMT_EXPR;
    stmt.expr = call;
    dxil_ir_append_stmt(function, &stmt, &stmt1);
    memset(&expr, 0, sizeof(expr));
    expr.kind = DXIL_IR_EXPR_PARAM_REF;
    expr.ty = vec3_ty;
    expr.index = 0;
    dxil_ir_append_expr(function, &expr, &gid_ref);
    memset(&expr, 0, sizeof(expr));
    expr.kind = DXIL_IR_EXPR_MEMBER;
    expr.ty = u32_ty;
    expr.base = gid_ref;
    expr.field_name = "x";
    expr.field_index = 0;
    dxil_ir_append_expr(function, &expr, &member);
    memset(&expr, 0, sizeof(expr));
    expr.kind = DXIL_IR_EXPR_INT_LIT;
    expr.ty = u32_ty;
    expr.uint_value = 1;
    dxil_ir_append_expr(function, &expr, &one);
    memset(&expr, 0, sizeof(expr));
    expr.kind = DXIL_IR_EXPR_BINARY;
    expr.ty = u32_ty;
    expr.binary_op = DXIL_IR_BINARY_ADD;
    expr.lhs = member;
    expr.rhs = one;
    dxil_ir_append_expr(function, &expr, &add);
    memset(&expr, 0, sizeof(expr));
    expr.kind = DXIL_IR_EXPR_GLOBAL_REF;
    expr.ty = arr_id;
    expr.index = 0;
    dxil_ir_append_expr(function, &expr, &gref);
    memset(&expr, 0, sizeof(expr));
    expr.kind = DXIL_IR_EXPR_INDEX;
    expr.ty = u32_ty;
    expr.base = gref;
    expr.index_expr = member;
    dxil_ir_append_expr(function, &expr, &index);
    memset(&stmt, 0, sizeof(stmt));
    stmt.kind = DXIL_IR_STMT_ASSIGN;
    stmt.assign_op = DXIL_IR_ASSIGN_ASSIGN;
    stmt.assign_lhs = index;
    stmt.assign_rhs = add;
    dxil_ir_append_stmt(function, &stmt, &stmt2);
    dxil_ir_append_stmt_child(function, stmt1);
    dxil_ir_append_stmt_child(function, stmt2);
    memset(&block, 0, sizeof(block));
    block.kind = DXIL_IR_STMT_BLOCK;
    block.range.start = 0;
    block.range.len = 2;
    dxil_ir_append_stmt(function, &block, &block_id);
    function->root_stmt = block_id;
    add_compute_entry(&module, function);
    CHECK_STATUS(dxil_hlsl_emit(&module, out, sizeof(out),
        &written), DXIL_OK);
    CHECK(written == strlen(expected));
    CHECK(strcmp(out, expected) == 0);
}

