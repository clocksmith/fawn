"""Generate the C toggle-effect table from config/quirk-toggle-registry.json, as
doe-zig-runtime embeds the same file at build time (quirk/toggle_registry.zig)."""

from __future__ import annotations

import json
import sys
from pathlib import Path

EFFECTS = {"behavioral": "DOE_TOGGLE_BEHAVIORAL", "informational": "DOE_TOGGLE_INFORMATIONAL"}


def main() -> int:
    source, out = Path(sys.argv[1]), Path(sys.argv[2])
    registry = json.loads(source.read_text(encoding="utf-8"))
    if registry.get("schemaVersion") != 1 or not isinstance(registry.get("toggles"), list):
        raise SystemExit(f"{source}: expected schemaVersion 1 with a toggles list")
    rows = []
    for entry in registry["toggles"]:
        name, effect = entry["toggle_name"], entry["effect"]
        if effect not in EFFECTS or not name.isascii() or '"' in name or "\\" in name:
            raise SystemExit(f"{source}: invalid toggle entry {entry!r}")
        rows.append(f'    {{"{name}", {EFFECTS[effect]}}},')
    out.write_text(
        "/* SPDX-License-Identifier: MIT\n * Generated by tools/gen_toggle_registry.py from "
        "config/quirk-toggle-registry.json. */\n#include \"quirks.h\"\n\n"
        "const doe_toggle_entry DOE_TOGGLE_REGISTRY[] = {\n" + "\n".join(rows) + "\n};\n"
        f"const size_t DOE_TOGGLE_REGISTRY_COUNT = {len(rows)};\n",
        encoding="utf-8",
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
