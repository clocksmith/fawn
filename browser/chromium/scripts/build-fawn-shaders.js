// Compile the retained demo shader definitions into an importable cycle bundle.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import vm from 'node:vm';
const resources = new URL('../resources/', import.meta.url);
const formation = readFileSync(new URL('fawn-formation.js', resources), 'utf8');
const context = vm.createContext({});
vm.runInContext(formation, context);
const definitions = {
  flow: [
    'fawn-prismatic-fluids.html',
    [
      'ADVECT_VEL_WGSL',
      'DIV_CURL_WGSL',
      'PRESSURE_WGSL',
      'PROJECT_WGSL',
      'ADVECT_DYE_WGSL',
      'RENDER_WGSL',
      'FLOW_MATERIAL',
      'PRESSURE_ITERATIONS',
      'WORKGROUP_SIZE',
    ],
  ],
  wave: [
    'fawn-magnetic-fluids.html',
    ['COMPUTE_WGSL', 'RENDER_WGSL', 'WAVE_UNIFORM_FLOATS', 'WORKGROUP_SIZE', 'updateWaveSources'],
  ],
  particles: [
    'fawn-start.html',
    [
      'COMPUTE_WGSL',
      'PARTICLE_WGSL',
      'FADE_WGSL',
      'PARTICLE_BLEND',
      'WORKGROUP_SIZE',
      'PARTICLE_RADIUS_PX',
    ],
  ],
};
const hashes = { 'fawn-formation.js': createHash('sha256').update(formation).digest('hex') };
let output = '// Generated by build-fawn-shaders.js from the retained standalone demos.\n';
for (const [effect, [file, names]] of Object.entries(definitions)) {
  const html = readFileSync(new URL(file, resources), 'utf8');
  hashes[file] = createHash('sha256').update(html).digest('hex');
  const sandbox = vm.createContext({ FawnFormation: context.FawnFormation });
  vm.runInContext(html.split('<script>')[1].split('(async () => {')[0], sandbox);
  const values = Object.fromEntries(names.map((name) => [name, vm.runInContext(name, sandbox)]));
  const fn = values.updateWaveSources;
  delete values.updateWaveSources;
  output += `export const ${effect} = Object.freeze(${JSON.stringify(values, null, 2)});\n`;
  if (fn)
    output += `export const updateWaveSources = ${fn
      .toString()
      .replaceAll('WAVE_ACTIVITY', String(vm.runInContext('WAVE_ACTIVITY', sandbox)))
      .replaceAll('MAGNET_COUNT', String(vm.runInContext('MAGNET_COUNT', sandbox)))
      .replaceAll('BUBBLE_COUNT', String(vm.runInContext('BUBBLE_COUNT', sandbox)))};\n`;
}
output += `export const sourceHashes = Object.freeze(${JSON.stringify(hashes, null, 2)});\n`;
const target = new URL('fawn-shaders.js', resources);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output)
    throw new Error('Fawn shader bundle is stale; run build-fawn-shaders.js');
} else writeFileSync(target, output);
