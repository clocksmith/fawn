import assert from 'node:assert/strict';
import { mkdtempSync, rmSync, writeFileSync, symlinkSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { InvestigationStore } from '../../src/client/investigation.js';
import { repositoryEvidence } from '../../src/client/repository.js';
import { sha256Hex } from '../../src/journal.js';
const root = mkdtempSync(join(tmpdir(), 'fawn-investigation-'));
let store;
try {
  store = new InvestigationStore(join(root, 'state'));
  store.create({ id: 'case', goal: 'Investigate a regression' });
  const evidence = store.revise('case', { kind: 'evidence', text: 'Saved code', source: { content: 'return 1;', sha256: sha256Hex('return 1;') } });
  const assumption = store.revise('case', { kind: 'assumption', text: 'Requests are serialized', dependsOn: [evidence.id] });
  const finding = store.revise('case', { kind: 'finding', text: 'No race is possible', dependsOn: [assumption.id] });
  const decision = store.revise('case', { kind: 'decision', text: 'Keep the current flow', dependsOn: [finding.id] });
  const recordBefore = JSON.stringify(store.journal.records);
  store.revise('case', { ...assumption, text: 'Requests can overlap', expectedRevision: 1 });
  const changed = store.get('case');
  assert.equal(changed.artifacts[finding.id].status, 'needs-review');
  assert.equal(changed.artifacts[decision.id].status, 'needs-review');
  assert.equal(changed.artifacts[evidence.id].status, 'current');
  assert.ok(JSON.stringify(store.journal.records).startsWith(recordBefore.slice(0, -1)), 'Derived invalidation must not mutate earlier journal records');
  assert.throws(() => store.revise('case', { ...assumption, expectedRevision: 1 }), /changed/);
  assert.throws(() => store.revise('case', { ...assumption, dependsOn: [decision.id], expectedRevision: 2 }), /cycle/);
  assert.throws(() => store.revise('case', { kind: 'evidence', text: 'invented', source: { content: 'a', sha256: 'bad' } }), /saved source bytes/);
  store.close(); store = new InvestigationStore(join(root, 'state'));
  assert.deepEqual(store.get('case').artifacts, changed.artifacts);
  writeFileSync(join(root, 'source.js'), 'export const value = 1;');
  writeFileSync(join(root, 'outside.txt'), 'not in selected repository');
  const repo = join(root, 'repo');
  const { mkdirSync } = await import('node:fs'); mkdirSync(repo);
  symlinkSync(join(root, 'outside.txt'), join(repo, 'escape'));
  await assert.rejects(repositoryEvidence(repo, 'escape', 1000), /escapes/);
  await assert.rejects(repositoryEvidence(repo, '../source.js', 1000), /escapes/);
  const source = await repositoryEvidence(root, 'source.js', 1000);
  assert.equal(source.sha256, sha256Hex(source.content));
  await assert.rejects(repositoryEvidence(root, 'source.js', 2), /bounded/);
  console.log('ok: investigation revisions, dependent invalidation, replay, source hashes and repository containment');
} finally { store?.close(); rmSync(root, { recursive: true, force: true }); }
